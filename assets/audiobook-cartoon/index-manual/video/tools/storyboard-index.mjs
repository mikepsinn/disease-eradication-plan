// Write storyboards/README.md: every part with its times and scene count, the props and gags
// that recur across the episode (build them once in assets/js/kit.js), the vertical shorts, and
// any scene name used twice (scene names must be unique across the episode).
//
//   node tools/storyboard-index.mjs
//
// The shorts come from storyboards/shorts.json: [{ name, part, from, to, why }], where from and
// to are scene names. Their times are read from the storyboards.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const VIDEO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BOARDS = join(VIDEO, "storyboards");
const { audio, parts } = JSON.parse(readFileSync(join(BOARDS, "parts.json"), "utf8"));

function mmss(t) {
  const r = Math.round(t);
  return `${Math.floor(r / 60)}:${String(r % 60).padStart(2, "0")}`;
}
function seconds(s) {
  const [m, x] = s.split(":");
  return Number(m) * 60 + Number(x);
}

const scenes = [];
const rows = [];
for (const p of parts) {
  const file = join(BOARDS, p.file);
  if (!existsSync(file)) {
    rows.push(`| ${p.n} | ${p.title} | ${mmss(p.start)} | ${mmss(p.end - p.start)} | | not written |`);
    continue;
  }
  const md = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const blocks = md.split(/\n## Scene \d+ · /).slice(1);
  const status = new Set();
  for (const b of blocks) {
    const f = { part: p.n };
    for (const line of b.split("\n")) {
      const m = line.match(/^- (\w+): (.*)$/);
      if (m) f[m[1]] = m[2];
    }
    const t = (f.time || "").match(/^(\d+:\d+\.\d) to (\d+:\d+\.\d)/);
    f.start = t ? seconds(t[1]) : null;
    f.end = t ? seconds(t[2]) : null;
    status.add(f.status || "outline");
    scenes.push(f);
  }
  rows.push(`| ${p.n} | [${p.title}](${p.file}) | ${mmss(p.start)} | ${mmss(p.end - p.start)} | ${blocks.length} | ${[...status].join(", ")} |`);
}

const names = new Map();
for (const s of scenes) names.set(s.id, [...(names.get(s.id) || []), s.part]);
const dupes = [...names].filter(([, ps]) => ps.length > 1);

const props = new Map();
for (const s of scenes) {
  for (const prop of (s.props || "").split(",").map((x) => x.trim()).filter(Boolean)) {
    if (!props.has(prop)) props.set(prop, { scenes: 0, parts: new Set() });
    const e = props.get(prop);
    e.scenes++;
    e.parts.add(s.part);
  }
}
const recurring = [...props].filter(([, e]) => e.scenes > 1).sort((a, b) => b[1].scenes - a[1].scenes);
const oneOff = [...props].filter(([, e]) => e.scenes === 1).map(([n]) => n).sort();

const shortsPath = join(BOARDS, "shorts.json");
const shorts = existsSync(shortsPath) ? JSON.parse(readFileSync(shortsPath, "utf8")) : [];
const shortRows = shorts.map((sh) => {
  const a = scenes.find((s) => s.id === sh.from), b = scenes.find((s) => s.id === sh.to);
  const span = a && b && a.start !== null && b.end !== null ? `${mmss(a.start)}–${mmss(b.end)} (${mmss(b.end - a.start)})` : "scene names not found";
  return `| ${sh.name} | ${sh.part} | ${sh.from} → ${sh.to} | ${span} | ${sh.why} |`;
});

const total = parts[parts.length - 1].end;
const out = `# Episode 1 cartoon: storyboards

Generated by \`tools/storyboard-index.mjs\` from the part storyboards; do not edit. Audio: \`${audio}\` (${mmss(total)}). Times in each storyboard come from its cue words (\`tools/storyboard-times.mjs\`).

## Parts

| # | Part | Starts | Length | Scenes | Status |
|---|---|---|---|---|---|
${rows.join("\n")}

${scenes.length} scenes in all.${dupes.length ? `\n\n**Scene names used twice:** ${dupes.map(([n, ps]) => `${n} (parts ${ps.join(", ")})`).join("; ")}. Rename one of each.` : ""}

## Vertical shorts

Self-contained segments to cut as 9:16 shorts, each with a hook in its first seconds and a payoff.

${shortRows.length ? `| Short | Part | Scenes | Time | Why |\n|---|---|---|---|---|\n${shortRows.join("\n")}` : "None picked yet."}

## Recurring props and gags

Build each of these once in \`assets/js/kit.js\`, most-used first.

| Prop | Scenes | Parts |
|---|---|---|
${recurring.map(([n, e]) => `| ${n} | ${e.scenes} | ${[...e.parts].join(", ")} |`).join("\n")}

Used once: ${oneOff.join(", ") || "none"}.
`;
writeFileSync(join(BOARDS, "README.md"), out);
console.log(`README.md: ${parts.length} parts, ${scenes.length} scenes, ${recurring.length} recurring props, ${shorts.length} shorts${dupes.length ? `, ${dupes.length} duplicate names` : ""}`);
