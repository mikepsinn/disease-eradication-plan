"""Write assets/js/art-sizes.js: the pixel size of every cut-out in assets/art/collage/, for KIT.collage.

    python -I tools/art-sizes.py

tools/art-cutout.py runs it after cutting into that folder, so a new cut-out never needs a hand-written size.
"""
import json
import sys
from pathlib import Path

from PIL import Image

sys.stdout.reconfigure(encoding="utf-8")  # type: ignore

VIDEO = Path(__file__).resolve().parent.parent
art = VIDEO / "assets" / "art" / "collage"
sizes = {}
for p in sorted(art.glob("*.webp")):
    try:
        sizes[p.stem] = list(Image.open(p).size)
    except OSError:  # another cut is still writing it; its own refresh will add it
        print(f"skipped {p.name}")
out = VIDEO / "assets" / "js" / "art-sizes.js"
out.write_text("// Generated by tools/art-sizes.py from assets/art/collage/. Do not edit.\nwindow.KIT_ART_SIZES = " + json.dumps(sizes, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"{len(sizes)} cut-outs")
