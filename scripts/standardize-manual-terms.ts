function extractManualQmdFiles(configDoc: any): ManualFileEntry[] {
  const fileParts = new Map<string, Set<string>>();

  const addFile = (relativePath: string, partName?: string) => {
    const parts = fileParts.get(relativePath) ?? new Set<string>();
    if (partName) {
      parts.add(partName);
    }
    fileParts.set(relativePath, parts);
  };

  const visit = (items: any[], currentPart?: string) => {
    if (!Array.isArray(items)) return;
    for (const item of items) {
      if (typeof item === 'string') {
        if (item.endsWith('.qmd')) addFile(item, currentPart);
        continue;
      }
      if (!item || typeof item !== 'object') continue;
      if (typeof item.href === 'string' && item.href.endsWith('.qmd')) {
        addFile(item.href, currentPart);
      }
      if (Array.isArray(item.chapters)) {
        visit(item.chapters, typeof item.part === 'string' ? item.part : currentPart);
      }
      if (Array.isArray(item.contents)) {
        visit(item.contents, currentPart);
      }
    }
  };

  visit(configDoc?.book?.chapters ?? []);
  return [...fileParts.entries()].map(([relativePath, parts]) => ({
    relativePath,
    partNames: [...parts],
  }));
}

function splitFrontmatter(content: string): { frontmatter: string; body: string } {
  const match = content.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/);
  if (!match) {
    return { frontmatter: '', body: content };
  }
  const frontmatter = match[0];
  const body = content.slice(frontmatter.length);
  return { frontmatter, body };
}

function shouldSkipLine(line: string): boolean {
  const trimmed = line.trim();

  if (!trimmed) return false;

  if (/^#\|/.test(trimmed)) return true;
  if (/^(fig-cap|tbl-cap|fig-alt|fig-sc|cap-location)\s*:/.test(trimmed)) return true;
  if (/^!\[/.test(trimmed)) return true;
  if (/^<[^>]+>/.test(trimmed)) return true;
  if (/^:::\s*\{/.test(trimmed)) return true;

  return false;
}

const PROTECTED_INLINE_REGEX =
  /!\[[^\]]*]\([^)]+\)|\[[^\]]*]\([^)]+\)|`[^`]*`|https?:\/\/\S+|<[^>]+>|\[@[^\]]+\]/g;

function applyRulesToSegment(segment: string, ctx: RuleContext, counters: Map<string, number>): string {
  let result = segment;
  const replacements: Array<{ token: string; value: string }> = [];
  let tokenIndex = 0;

  for (const rule of RULES) {
    result = result.replace(rule.pattern, () => {
      const token = `__DIH_STANDARDIZE_${tokenIndex++}__`;
      replacements.push({ token, value: rule.replacement(ctx) });
      counters.set(rule.name, (counters.get(rule.name) ?? 0) + 1);
      return token;
    });
  }

  for (const replacement of replacements) {
    result = result.replaceAll(replacement.token, replacement.value);
  }

  return result;
}

function transformLine(line: string, ctx: RuleContext, counters: Map<string, number>): string {
  const normalizedLine = line.replace(/(!?)\[([^\]]+)]\(([^)]+)\)/g, (match, imageMarker, text, href) => {
    if (imageMarker) {
      return match;
    }
    for (const rule of RULES) {
      if (!rule.plainText) continue;
      if (!hrefMatchesRuleTarget(href, ctx, rule)) continue;
      const canonicalText = canonicalizeLinkedText(text, rule);
      if (isHomeFile(ctx, rule)) {
        return canonicalText;
      }
      if (text.trim() !== canonicalText && text.trim().toLowerCase() === canonicalText.toLowerCase()) {
        return `[${canonicalText}](${href})`;
      }
    }
    return match;
  });

  let output = '';
  let lastIndex = 0;
  let match: RegExpExecArray | null;

  PROTECTED_INLINE_REGEX.lastIndex = 0;
  while ((match = PROTECTED_INLINE_REGEX.exec(normalizedLine)) !== null) {
    output += applyRulesToSegment(normalizedLine.slice(lastIndex, match.index), ctx, counters);
    output += match[0];
    lastIndex = match.index + match[0].length;
  }
  output += applyRulesToSegment(normalizedLine.slice(lastIndex), ctx, counters);
  return output;
}

function transformBody(
  body: string,
  filePath: string,
  relativePath: string,
  partNames: string[],
  title?: string
): { changed: boolean; body: string; counters: Map<string, number> } {
  const counters = new Map<string, number>();
  const newline = body.includes('\r\n') ? '\r\n' : '\n';
  const lines = body.split(/\r?\n/);
  const out: string[] = [];

  let inFence = false;
  let fenceMarker = '';
  let inMathBlock = false;
  let inHtmlComment = false;

  const ctx: RuleContext = {
    filePath,
    relativePath,
    rootDir: ROOT_DIR,
    partNames,
    title,
    baseName: path.basename(filePath, path.extname(filePath)),
  };

  for (const line of lines) {
    const trimmed = line.trim();

    if (inHtmlComment) {
      out.push(line);
      if (trimmed.includes('-->')) {
        inHtmlComment = false;
      }
      continue;
    }

    if (inFence) {
      out.push(line);
      if (trimmed.startsWith(fenceMarker)) {
        inFence = false;
        fenceMarker = '';
      }
      continue;
    }

    if (inMathBlock) {
      out.push(line);
      if (trimmed === '$$') {
        inMathBlock = false;
      }
      continue;
    }

    if (trimmed.startsWith('<!--')) {
      out.push(line);
      if (!trimmed.includes('-->')) {
        inHtmlComment = true;
      }
      continue;
    }

    const fenceMatch = trimmed.match(/^(```|~~~)/);
    if (fenceMatch) {
      out.push(line);
      inFence = true;
      fenceMarker = fenceMatch[1];
      continue;
    }

    if (trimmed === '$$') {
      out.push(line);
      inMathBlock = true;
      continue;
    }

    if (shouldSkipLine(line)) {
      out.push(line);
      continue;
    }

    out.push(transformLine(line, ctx, counters));
  }

  const newBody = out.join(newline);
  return {
    changed: newBody !== body,
    body: newBody,
    counters,
  };
}

async function main() {
  const args = parseArgs();
  const configPath = path.join(ROOT_DIR, args.configFile);
  const configContent = await fs.readFile(configPath, 'utf-8');
  const configDoc = yaml.load(configContent) as any;

  const candidateFiles = extractManualQmdFiles(configDoc)
    .map(entry => ({
      ...entry,
      absolutePath: path.join(ROOT_DIR, entry.relativePath),
    }))
    .filter(entry => !isAutoGeneratedFile(entry.absolutePath));

  const files: Array<ManualFileEntry & { absolutePath: string }> = [];
  for (const entry of candidateFiles) {
    if (await pathExists(entry.absolutePath)) {
      files.push(entry);
    } else if (args.verbose) {
      console.warn(`[skip missing] ${entry.relativePath}`);
    }
  }

  const fileChanges: FileChange[] = [];
  const totalCounters = new Map<string, number>();

  for (const file of files) {
    const original = await fs.readFile(file.absolutePath, 'utf-8');
    const { frontmatter, body } = splitFrontmatter(original);
    let title: string | undefined;
    if (frontmatter) {
      try {
        const frontmatterDoc = yaml.load(
          frontmatter.replace(/^---\r?\n/, '').replace(/\r?\n---\r?\n?$/, '')
        ) as any;
        if (frontmatterDoc && typeof frontmatterDoc.title === 'string') {
          title = frontmatterDoc.title;
        }
      } catch {
        // Ignore frontmatter parse failures and fall back to basename matching.
      }
    }
    const transformed = transformBody(body, file.absolutePath, file.relativePath, file.partNames, title);

    if (!transformed.changed) {
      continue;
    }

    if (!args.dryRun) {
      await fs.writeFile(file.absolutePath, frontmatter + transformed.body, 'utf-8');
    }

    let fileCount = 0;
    for (const [ruleName, count] of transformed.counters.entries()) {
      if (count > 0) {
        totalCounters.set(ruleName, (totalCounters.get(ruleName) ?? 0) + count);
        fileCount += count;
      }
    }

    fileChanges.push({
      file: file.relativePath,
      changes: fileCount,
    });

    if (args.verbose) {
      console.log(`${args.dryRun ? '[dry-run] ' : ''}${file.relativePath} (${fileCount} changes)`);
    }
  }

  console.log(`Scanned ${files.length} manual QMD files.`);
  console.log(`${args.dryRun ? 'Would change' : 'Changed'} ${fileChanges.length} files.`);

  if (fileChanges.length > 0) {
    console.log('\nFiles:');
    for (const detail of fileChanges) {
      console.log(`  ${detail.file} (${detail.changes})`);
    }

    console.log('\nRule counts:');
    for (const [ruleName, count] of [...totalCounters.entries()].sort((a, b) => b[1] - a[1])) {
      console.log(`  ${ruleName}: ${count}`);
    }
  }
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
