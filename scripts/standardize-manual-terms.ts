interface Args {
  dryRun: boolean;
  verbose: boolean;
  configFile: string;
}

interface RuleContext {
  filePath: string;
  relativePath: string;
  rootDir: string;
  partNames: string[];
  title?: string;
  baseName: string;
}

interface Rule {
  name: string;
  pattern: RegExp;
  plainText?: string;
  targetRelativePath?: string;
  externalHref?: string;
  homeFiles?: string[];
  topicAliases?: string[];
  replacement: (ctx: RuleContext) => string;
}

interface FileChange {
  file: string;
  changes: number;
}

interface ManualFileEntry {
  relativePath: string;
  partNames: string[];
}

const ROOT_DIR = getProjectRoot();
const KEY_TOPIC_PARTS = new Set(['System Optimization', 'Papers & Publications']);

async function pathExists(filePath: string): Promise<boolean> {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

function parseArgs(): Args {
  const args = process.argv.slice(2);
  const parsed: Args = {
    dryRun: false,
    verbose: false,
    configFile: '_quarto-manual.yml',
  };

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--dry-run') {
      parsed.dryRun = true;
    } else if (arg === '--verbose') {
      parsed.verbose = true;
    } else if (arg === '--config' && i + 1 < args.length) {
      parsed.configFile = args[++i];
    }
  }

  return parsed;
}

function getRelativeHref(fromFile: string, toFile: string): string {
  const relative = path.relative(path.dirname(fromFile), toFile).replace(/\\/g, '/');
  return relative || path.basename(toFile);
}

function makeLink(ctx: RuleContext, targetRelativePath: string, text: string): string {
  const targetPath = path.join(ctx.rootDir, targetRelativePath);
  const normalizedCurrent = path.resolve(ctx.filePath);
  const normalizedTarget = path.resolve(targetPath);
  if (normalizedCurrent === normalizedTarget) {
    return text;
  }
  return `[${text}](${getRelativeHref(ctx.filePath, normalizedTarget)})`;
}

function makeExternalLink(text: string, href: string): string {
  return `[${text}](${href})`;
}

function normalizeTopicKey(value: string): string {
  return value
    .toLowerCase()
    .replace(/%/g, ' pct ')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function isInKeyTopicPart(ctx: RuleContext): boolean {
  return ctx.partNames.some(partName => KEY_TOPIC_PARTS.has(partName));
}

function matchesTopicAlias(ctx: RuleContext, alias: string): boolean {
  const normalizedAlias = normalizeTopicKey(alias);
  if (!normalizedAlias) {
    return false;
  }

  const candidates = [ctx.title, ctx.baseName]
    .filter((value): value is string => Boolean(value))
    .map(normalizeTopicKey);

  return candidates.some(candidate =>
    candidate === normalizedAlias ||
    candidate.startsWith(`${normalizedAlias} `)
  );
}

function isInferredHomeFile(ctx: RuleContext, rule: Rule): boolean {
  if (!isInKeyTopicPart(ctx)) {
    return false;
  }

  const aliases = rule.topicAliases ?? (rule.plainText ? [rule.plainText] : []);
  return aliases.some(alias => matchesTopicAlias(ctx, alias));
}

function isHomeFile(ctx: RuleContext, rule: Rule): boolean {
  if (rule.homeFiles && rule.homeFiles.length > 0) {
    const current = path.resolve(ctx.filePath);
    if (rule.homeFiles.some(homeFile => current === path.resolve(path.join(ctx.rootDir, homeFile)))) {
      return true;
    }
  }
  return isInferredHomeFile(ctx, rule);
}

function linkOrPlain(ctx: RuleContext, rule: Rule): string {
  if (!rule.plainText) {
    throw new Error(`Rule ${rule.name} is missing plainText`);
  }
  if (isHomeFile(ctx, rule)) {
    return rule.plainText;
  }
  if (rule.targetRelativePath) {
    return makeLink(ctx, rule.targetRelativePath, rule.plainText);
  }
  if (rule.externalHref) {
    return makeExternalLink(rule.plainText, rule.externalHref);
  }
  return rule.plainText;
}

function hrefMatchesRuleTarget(href: string, ctx: RuleContext, rule: Rule): boolean {
  if (rule.targetRelativePath) {
    const absoluteHref = path.resolve(path.dirname(ctx.filePath), href);
    const absoluteTarget = path.resolve(path.join(ctx.rootDir, rule.targetRelativePath));
    return absoluteHref === absoluteTarget;
  }
  if (rule.externalHref) {
    return href === rule.externalHref;
  }
  return false;
}

function canonicalizeLinkedText(text: string, rule: Rule): string {
  if (!rule.plainText) {
    return text;
  }
  const trimmed = text.trim();
  if (trimmed.toLowerCase() === `the ${rule.plainText.toLowerCase()}`) {
    return `The ${rule.plainText}`;
  }
  return rule.plainText;
}

function createLinkOrPlainReplacement(
  plainText: string,
  options: { targetRelativePath?: string; externalHref?: string; homeFiles?: string[] } = {}
): (ctx: RuleContext) => string {
  return (ctx: RuleContext) =>
    linkOrPlain(ctx, {
      name: plainText,
      pattern: /$^/,
      plainText,
      targetRelativePath: options.targetRelativePath,
      externalHref: options.externalHref,
      homeFiles: options.homeFiles,
      replacement: () => plainText,
    });
}

